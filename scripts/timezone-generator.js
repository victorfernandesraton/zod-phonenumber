export function renderTimezoneModule(regions, source = '@vvo/tzdb') {
  const entries = Object.entries(regions)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([timezone, region]) => `  ${JSON.stringify(timezone)}: ${JSON.stringify(region)},`)
  return `// Generated by scripts/generate-timezone-regions.js from ${source}.\nexport const timezoneRegions = {\n${entries.join('\n')}\n} as const\n`
}
